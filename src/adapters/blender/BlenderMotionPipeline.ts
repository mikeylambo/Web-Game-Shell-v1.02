import type { MotionImpactPackage } from "../../motion/package.js";
import type { AdapterArtifact, MotionImpactAdapterOptions, MotionImpactEngineAdapter } from "../MotionImpactAdapter.js";

export interface BlenderMotionJob {
  sourceFile: string;
  targetRigObject?: string;
  sourceArmatureObject?: string;
  actionName?: string;
  outputGlb?: string;
  applyRootMotion?: boolean;
  targetFps?: number;
}

export function createBlenderMotionJobScript(job: BlenderMotionJob): string {
  const config = JSON.stringify(job);
  return `# Generated by SLU Motion/Impact\nimport bpy, json, os\n\nJOB = json.loads(${JSON.stringify(config)})\n\ndef active_armature(name=None):\n    if name and name in bpy.data.objects:\n        return bpy.data.objects[name]\n    for obj in bpy.context.scene.objects:\n        if obj.type == 'ARMATURE':\n            return obj\n    return None\n\ndef clear_scene():\n    bpy.ops.object.select_all(action='SELECT')\n    bpy.ops.object.delete(use_global=False)\n\ndef import_motion(path):\n    ext = os.path.splitext(path)[1].lower()\n    if ext == '.fbx':\n        bpy.ops.import_scene.fbx(filepath=path)\n    elif ext in ('.glb', '.gltf'):\n        bpy.ops.import_scene.gltf(filepath=path)\n    elif ext == '.bvh':\n        bpy.ops.import_anim.bvh(filepath=path)\n    else:\n        raise RuntimeError('Unsupported motion source: ' + ext)\n\ndef normalize_scene():\n    bpy.context.scene.render.fps = int(JOB.get('targetFps') or 60)\n    for obj in bpy.context.scene.objects:\n        if obj.type == 'ARMATURE':\n            obj.rotation_euler[0] = 0.0\n            obj.rotation_euler[1] = 0.0\n\ndef export_glb(path):\n    bpy.ops.export_scene.gltf(filepath=path, export_format='GLB', export_animations=True, export_skins=True)\n\nclear_scene()\nimport_motion(JOB['sourceFile'])\nnormalize_scene()\narmature = active_armature(JOB.get('sourceArmatureObject'))\nif armature is None:\n    raise RuntimeError('No armature found in mocap source')\n\nprint('[SLU] Armature:', armature.name)\nprint('[SLU] Bones:', json.dumps([b.name for b in armature.data.bones]))\nif armature.animation_data and armature.animation_data.action:\n    action = armature.animation_data.action\n    print('[SLU] Action:', action.name)\n    print('[SLU] Frames:', action.frame_range[:])\n\nout = JOB.get('outputGlb')\nif out:\n    export_glb(out)\n    print('[SLU] Exported:', out)\n`;
}

export class BlenderMotionPipelineAdapter implements MotionImpactEngineAdapter {
  readonly id = "blender-motion";
  readonly displayName = "Blender Motion Pipeline";

  exportPackage(pkg: MotionImpactPackage, options: MotionImpactAdapterOptions = {}): AdapterArtifact[] {
    const jobs = pkg.clips.map((clip) => ({
      clipId: clip.id,
      sourceFile: clip.assetUri,
      targetRigId: clip.targetRigId,
      rootMotion: clip.rootMotion,
      fps: clip.fps,
    }));
    return [
      { path: "slu/blender-motion-jobs.json", content: JSON.stringify(jobs, null, 2), kind: "config" },
      { path: "slu/README.md", content: "# Blender Motion Pipeline\n\nUse Blender as the binary FBX/BVH/GLB processing stage. SLU remains the semantic source of truth for rig mapping, retarget plans, markers, root-motion policy, and impact bindings. Generate one job script per source clip, run it in Blender, then feed the normalized GLB back to the target engine adapter.\n", kind: "documentation" },
    ];
  }
}
